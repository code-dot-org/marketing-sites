/**
 * Regenerates src/components/dataDisplay/map/usStatePaths.ts from us-atlas
 * (Census boundaries, already projected to Albers USA at 975×610).
 *
 * Run from apps/marketing: yarn tsx scripts/generateUsStatePaths.ts
 */
import {geoPath} from 'd3-geo';
import {writeFileSync} from 'node:fs';
import path from 'node:path';
import {feature} from 'topojson-client';
import {presimplify, simplify} from 'topojson-simplify';
import type {GeometryCollection, Topology} from 'topojson-specification';
import states from 'us-atlas/states-albers-10m.json';

// Planar area threshold in square pixels: small enough to keep RI and DE legible.
const MIN_WEIGHT = 1;

const FIPS_TO_POSTAL: Record<string, string> = {
  '01': 'AL',
  '02': 'AK',
  '04': 'AZ',
  '05': 'AR',
  '06': 'CA',
  '08': 'CO',
  '09': 'CT',
  '10': 'DE',
  '11': 'DC',
  '12': 'FL',
  '13': 'GA',
  '15': 'HI',
  '16': 'ID',
  '17': 'IL',
  '18': 'IN',
  '19': 'IA',
  '20': 'KS',
  '21': 'KY',
  '22': 'LA',
  '23': 'ME',
  '24': 'MD',
  '25': 'MA',
  '26': 'MI',
  '27': 'MN',
  '28': 'MS',
  '29': 'MO',
  '30': 'MT',
  '31': 'NE',
  '32': 'NV',
  '33': 'NH',
  '34': 'NJ',
  '35': 'NM',
  '36': 'NY',
  '37': 'NC',
  '38': 'ND',
  '39': 'OH',
  '40': 'OK',
  '41': 'OR',
  '42': 'PA',
  '44': 'RI',
  '45': 'SC',
  '46': 'SD',
  '47': 'TN',
  '48': 'TX',
  '49': 'UT',
  '50': 'VT',
  '51': 'VA',
  '53': 'WA',
  '54': 'WV',
  '55': 'WI',
  '56': 'WY',
};

const topology = simplify(
  presimplify(states as unknown as Topology<{states: GeometryCollection}>),
  MIN_WEIGHT,
) as Topology<{states: GeometryCollection}>;

const collection = feature(topology, topology.objects.states);
const pathOf = geoPath().digits(1);

const paths: Record<string, string> = {};
let dcCentroid: [number, number] | null = null;

for (const f of collection.features) {
  const postal = FIPS_TO_POSTAL[String(f.id)];
  if (!postal) {
    continue; // territories
  }
  paths[postal] = pathOf(f) ?? '';
  if (postal === 'DC') {
    dcCentroid = pathOf.centroid(f);
  }
}

if (Object.keys(paths).length !== 51 || !dcCentroid) {
  throw new Error(
    `Expected 51 jurisdictions, got ${Object.keys(paths).length}`,
  );
}

// DC is too small to hover; a callout circle sits out to the east, in the Atlantic.
const dcCallout = {
  cx: Math.round(dcCentroid[0] + 48),
  cy: Math.round(dcCentroid[1] + 22),
  r: 9,
  anchor: dcCentroid.map(v => Math.round(v * 10) / 10),
};

const sorted = Object.fromEntries(
  Object.entries(paths).sort(([a], [b]) => a.localeCompare(b)),
);

const output = `// Generated by scripts/generateUsStatePaths.ts from us-atlas@3.0.1
// (states-albers-10m). Do not edit by hand.

export const US_MAP_VIEWBOX = '0 0 975 610';

export const US_DC_CALLOUT = ${JSON.stringify(dcCallout)} as const;

export const US_STATE_PATHS: Record<string, string> = ${JSON.stringify(sorted, null, 2)};
`;

const target = path.resolve(
  __dirname,
  '../src/components/dataDisplay/map/usStatePaths.ts',
);
writeFileSync(target, output);
console.log(`Wrote ${target} (${output.length} bytes)`);
